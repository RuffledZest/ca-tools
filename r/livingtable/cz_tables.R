## tau of a species: number of unequal pairs. Binary weight w: w (t - w).
## Ternary partition (s1, s2, s3): s1 s2 + s1 s3 + s2 s3.
tau_ternary <- function(t) { out <- c(); for (s1 in t:1) for (s2 in min(s1, t - s1):0) { s3 <- t - s1 - s2; if (s3 > s2) next
    out <- c(out, s1 * s2 + s1 * s3 + s2 * s3) }; sort(unique(out)) }
